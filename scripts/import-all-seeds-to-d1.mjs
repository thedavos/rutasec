#!/usr/bin/env node
import fs from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

import { EDITORIAL_SEED_PATHS, IMPORT_SQL_PATH } from "./lib/editorial-seed-paths.mjs";
import { buildSql } from "./import-seed-to-d1.mjs";
import { validateSeed } from "./lib/validate-seed.mjs";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const projectRoot = path.resolve(__dirname, "..");

function usage() {
  console.log(`Usage:
  npm run db:seed:sql:all [--out sql-file]

Examples:
  npm run db:seed:sql:all
  node scripts/import-all-seeds-to-d1.mjs --out db/seed/import.sql

What it does:
  - Validates and generates SQL for all editorial seed files:
    ${EDITORIAL_SEED_PATHS.join(", ")}
  - Writes combined idempotent SQL to db/seed/import.sql (default)
`);
}

async function main() {
  const args = process.argv.slice(2);

  if (args.includes("--help") || args.includes("-h")) {
    usage();
    process.exit(0);
  }

  let outPath = path.join(projectRoot, IMPORT_SQL_PATH);

  for (let i = 0; i < args.length; i += 1) {
    const arg = args[i];
    if (arg === "--out") {
      outPath = args[i + 1];
      i += 1;
    }
  }

  const sqlParts = [
    "-- Generated by scripts/import-all-seeds-to-d1.mjs",
    `-- Seeds: ${EDITORIAL_SEED_PATHS.join(", ")}`,
    "",
  ];

  for (const relativeSeedPath of EDITORIAL_SEED_PATHS) {
    const seedPath = path.join(projectRoot, relativeSeedPath);
    const raw = await fs.readFile(seedPath, "utf8");
    const seed = JSON.parse(raw);
    validateSeed(seed);
    sqlParts.push(`-- ${relativeSeedPath}`);
    sqlParts.push(buildSql(seed, { includeBanner: sqlParts.length === 3 }).trim());
    sqlParts.push("");
  }

  const sql = `${sqlParts.join("\n")}\n`;
  const resolvedOutPath = path.resolve(process.cwd(), outPath);
  await fs.mkdir(path.dirname(resolvedOutPath), { recursive: true });
  await fs.writeFile(resolvedOutPath, sql, "utf8");
  console.log(`Wrote combined SQL import file to ${resolvedOutPath}`);
}

main().catch((error) => {
  console.error(`Combined import generation failed: ${error.message}`);
  process.exit(1);
});
