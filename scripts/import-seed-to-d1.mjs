#!/usr/bin/env node
import fs from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const projectRoot = path.resolve(__dirname, "..");

function usage() {
  console.log(`Usage:
  node scripts/import-seed-to-d1.mjs [seed.json] [--out sql-file]

Examples:
  node scripts/import-seed-to-d1.mjs
  node scripts/import-seed-to-d1.mjs db/seed/web-pentesting-starter.json --out db/seed/import.sql

What it does:
  - Reads a RutaSec seed JSON file
  - Validates the expected structure
  - Generates idempotent SQL for D1 import
  - Prints SQL to stdout or writes it to --out
`);
}

function sqlString(value) {
  if (value === null || value === undefined) return "NULL";
  return `'${String(value).replace(/'/g, "''")}'`;
}

function sqlBool(value) {
  return value ? "1" : "0";
}

function nowIso() {
  return new Date().toISOString();
}

function requireField(obj, field, context) {
  if (obj[field] === undefined || obj[field] === null || obj[field] === "") {
    throw new Error(`Missing required field '${field}' in ${context}`);
  }
}

function validateSeed(seed) {
  if (!seed || typeof seed !== "object") {
    throw new Error("Seed must be a JSON object");
  }

  if (!seed.learning_path || typeof seed.learning_path !== "object") {
    throw new Error("Seed must contain a learning_path object");
  }

  if (!Array.isArray(seed.resources) || seed.resources.length === 0) {
    throw new Error("Seed must contain a non-empty resources array");
  }

  const lp = seed.learning_path;
  ["id", "slug", "title", "description"].forEach((field) =>
    requireField(lp, field, "learning_path"),
  );

  const seenIds = new Set();
  const seenOrders = new Set();

  seed.resources.forEach((resource, index) => {
    const context = `resources[${index}]`;
    [
      "id",
      "title",
      "url",
      "phase",
      "category",
      "topic",
      "resource_type",
      "level",
      "estimated_hours",
      "original_source_name",
      "original_source_url",
      "curated_from_name",
      "curated_from_url",
      "roadmap_section",
      "path_order",
    ].forEach((field) => requireField(resource, field, context));

    if (seenIds.has(resource.id)) {
      throw new Error(`Duplicate resource id: ${resource.id}`);
    }
    seenIds.add(resource.id);

    if (seenOrders.has(resource.path_order)) {
      throw new Error(`Duplicate path_order: ${resource.path_order}`);
    }
    seenOrders.add(resource.path_order);

    if (!Array.isArray(resource.tags)) {
      throw new Error(`${context}.tags must be an array`);
    }

    const learningModes = ["theory", "practice", "mixed"];
    const hasLearningMode = resource.tags.some((tag) =>
      learningModes.includes(String(tag).trim().toLowerCase()),
    );
    if (!hasLearningMode) {
      throw new Error(`${context}.tags must include one of: ${learningModes.join(", ")}`);
    }
  });
}

function slugifyTag(tag) {
  return String(tag)
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function buildSql(seed) {
  const timestamp = nowIso();
  const statements = [];
  const tagMap = new Map();

  statements.push("-- Generated by scripts/import-seed-to-d1.mjs");
  statements.push(`-- Generated at ${timestamp}`);
  statements.push("BEGIN TRANSACTION;");

  const lp = seed.learning_path;
  statements.push(
    `
INSERT INTO learning_paths (
  id, slug, title, description, is_featured, is_published, created_at, updated_at
) VALUES (
  ${sqlString(lp.id)},
  ${sqlString(lp.slug)},
  ${sqlString(lp.title)},
  ${sqlString(lp.description)},
  ${sqlBool(Boolean(lp.is_featured))},
  ${sqlBool(lp.is_published !== false)},
  ${sqlString(timestamp)},
  ${sqlString(timestamp)}
)
ON CONFLICT(id) DO UPDATE SET
  slug = excluded.slug,
  title = excluded.title,
  description = excluded.description,
  is_featured = excluded.is_featured,
  is_published = excluded.is_published,
  updated_at = excluded.updated_at;`.trim(),
  );

  for (const resource of seed.resources) {
    statements.push(
      `
INSERT INTO resources (
  id, title, description, url,
  phase, category, topic, subtopic,
  resource_type, level, estimated_hours,
  original_source_name, original_source_url,
  curated_from_name, curated_from_url, roadmap_section,
  is_free, language, is_published, link_status, imported_at, created_at, updated_at
) VALUES (
  ${sqlString(resource.id)},
  ${sqlString(resource.title)},
  ${sqlString(resource.description ?? null)},
  ${sqlString(resource.url)},
  ${sqlString(resource.phase)},
  ${sqlString(resource.category)},
  ${sqlString(resource.topic)},
  ${sqlString(resource.subtopic ?? null)},
  ${sqlString(resource.resource_type)},
  ${sqlString(resource.level)},
  ${Number(resource.estimated_hours)},
  ${sqlString(resource.original_source_name)},
  ${sqlString(resource.original_source_url)},
  ${sqlString(resource.curated_from_name)},
  ${sqlString(resource.curated_from_url)},
  ${sqlString(resource.roadmap_section)},
  ${sqlBool(resource.is_free !== false)},
  ${sqlString(resource.language ?? null)},
  1,
  'unknown',
  ${sqlString(timestamp)},
  ${sqlString(timestamp)},
  ${sqlString(timestamp)}
)
ON CONFLICT(id) DO UPDATE SET
  title = excluded.title,
  description = excluded.description,
  url = excluded.url,
  phase = excluded.phase,
  category = excluded.category,
  topic = excluded.topic,
  subtopic = excluded.subtopic,
  resource_type = excluded.resource_type,
  level = excluded.level,
  estimated_hours = excluded.estimated_hours,
  original_source_name = excluded.original_source_name,
  original_source_url = excluded.original_source_url,
  curated_from_name = excluded.curated_from_name,
  curated_from_url = excluded.curated_from_url,
  roadmap_section = excluded.roadmap_section,
  is_free = excluded.is_free,
  language = excluded.language,
  is_published = excluded.is_published,
  imported_at = excluded.imported_at,
  updated_at = excluded.updated_at;`.trim(),
    );

    statements.push(
      `
INSERT INTO learning_path_items (
  id, learning_path_id, resource_id, item_order, notes, created_at
) VALUES (
  ${sqlString(`lpi-${lp.id}-${resource.path_order}`)},
  ${sqlString(lp.id)},
  ${sqlString(resource.id)},
  ${Number(resource.path_order)},
  NULL,
  ${sqlString(timestamp)}
)
ON CONFLICT(id) DO UPDATE SET
  learning_path_id = excluded.learning_path_id,
  resource_id = excluded.resource_id,
  item_order = excluded.item_order;`.trim(),
    );

    for (const rawTag of resource.tags) {
      const name = String(rawTag).trim();
      const slug = slugifyTag(name);
      const id = `tag-${slug}`;

      if (!tagMap.has(slug)) {
        tagMap.set(slug, { id, name, slug });
      }

      statements.push(
        `
INSERT INTO resource_tags (
  resource_id, tag_id, created_at
) VALUES (
  ${sqlString(resource.id)},
  ${sqlString(id)},
  ${sqlString(timestamp)}
)
ON CONFLICT(resource_id, tag_id) DO NOTHING;`.trim(),
      );
    }
  }

  for (const tag of tagMap.values()) {
    statements.splice(
      3,
      0,
      `INSERT INTO tags (id, name, slug, created_at) VALUES (
  ${sqlString(tag.id)},
  ${sqlString(tag.name)},
  ${sqlString(tag.slug)},
  ${sqlString(timestamp)}
)
ON CONFLICT(id) DO UPDATE SET
  name = excluded.name,
  slug = excluded.slug;`,
    );
  }

  statements.push(
    `
INSERT INTO resource_imports (
  id, source_name, source_url, import_type, imported_count, notes, created_at
) VALUES (
  ${sqlString(`import-${lp.slug}-${timestamp}`)},
  ${sqlString(seed.learning_path.title)},
  ${sqlString(seed.resources[0]?.curated_from_url ?? "")},
  'seed',
  ${seed.resources.length},
  ${sqlString(`Seed import for learning path ${lp.slug}`)},
  ${sqlString(timestamp)}
);`.trim(),
  );

  statements.push("COMMIT;");
  return `${statements.join("\n\n")}\n`;
}

async function main() {
  const args = process.argv.slice(2);

  if (args.includes("--help") || args.includes("-h")) {
    usage();
    process.exit(0);
  }

  let seedPath = path.join(projectRoot, "db/seed/web-pentesting-starter.json");
  let outPath = path.join(projectRoot, "db/seed/import.sql");

  for (let i = 0; i < args.length; i += 1) {
    const arg = args[i];
    if (arg === "--out") {
      outPath = args[i + 1];
      i += 1;
      continue;
    }
    if (!arg.startsWith("--")) {
      seedPath = arg;
    }
  }

  const resolvedSeedPath = path.resolve(process.cwd(), seedPath);
  const raw = await fs.readFile(resolvedSeedPath, "utf8");
  const seed = JSON.parse(raw);
  validateSeed(seed);

  const sql = buildSql(seed);

  if (outPath) {
    const resolvedOutPath = path.resolve(process.cwd(), outPath);
    await fs.mkdir(path.dirname(resolvedOutPath), { recursive: true });
    await fs.writeFile(resolvedOutPath, sql, "utf8");
    console.log(`Wrote SQL import file to ${resolvedOutPath}`);
    return;
  }

  process.stdout.write(sql);
}

main().catch((error) => {
  console.error(`Import generation failed: ${error.message}`);
  process.exit(1);
});
